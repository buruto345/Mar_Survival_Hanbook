using Mars_Survival_Hanbook.Contracts;
using Mars_Survival_Hanbook.Models;
namespace Mars_Survival_Hanbook.Services.Editorial;

internal static class ContentMapping
{
    public static ScientificFact ToEntity(FactRequest r, Guid sourceId) => new() { SourceId = sourceId, SourceRevisionId = r.SourceRevisionId,
        Name = r.Name,
        Value = r.Value,
        UpperValue = r.UpperValue,
        UnitId = r.UnitId,
        OriginalValue = r.OriginalValue,
        OriginalUnit = r.OriginalUnit,
        MeasurementKind = r.MeasurementKind,
        MeasurementContext = r.Context,
        Assumptions = r.Assumptions,
        Uncertainty = r.Uncertainty,
        EvidenceType = r.EvidenceType,
        TestEnvironment = r.TestEnvironment,
        ObservedAt = r.ObservedAt };
    public static FactRequest ToRequest(ScientificFact e) => new() { SourceRevisionId = e.SourceRevisionId ?? Guid.Empty,
        Name = e.Name,
        Value = e.Value,
        UpperValue = e.UpperValue,
        UnitId = e.UnitId,
        OriginalValue = e.OriginalValue,
        OriginalUnit = e.OriginalUnit,
        MeasurementKind = e.MeasurementKind,
        Context = e.MeasurementContext,
        Assumptions = e.Assumptions,
        Uncertainty = e.Uncertainty,
        EvidenceType = e.EvidenceType,
        TestEnvironment = e.TestEnvironment,
        ObservedAt = e.ObservedAt };
