        NASAIdentifier = r.NasaIdentifier,
        Name = r.Name,
        Agency = r.Agency,
        Description = r.Description,
        MissionType = r.MissionType,
        Status = r.Status,
        LaunchDate = r.LaunchDate,
        EndDate = r.EndDate,
        StatusVerifiedAt = r.StatusVerifiedAt };
    public static MissionRequest ToRequest(Mission e) => new() { SourceRevisionId = e.SourceRevisionId ?? Guid.Empty,
        NasaIdentifier = e.NASAIdentifier,
        Name = e.Name,
        Agency = e.Agency,
        Description = e.Description,
        MissionType = e.MissionType,
        Status = e.Status,
        LaunchDate = e.LaunchDate,
        EndDate = e.EndDate,
        StatusVerifiedAt = e.StatusVerifiedAt };
