        FactId = r.FactId,
        Value = r.Value,
        UpperValue = r.UpperValue,
        UnitId = r.UnitId,
        OriginalValue = r.OriginalValue,
        OriginalUnit = r.OriginalUnit,
        MeasurementKind = r.MeasurementKind,
        ObservedAt = r.ObservedAt,
        ObservationEndAt = r.ObservationEndAt,
        Instrument = r.Instrument,
        Conditions = r.Context,
        Uncertainty = r.Uncertainty,
        EvidenceType = r.EvidenceType,
        TestEnvironment = r.TestEnvironment,
        MissionId = r.MissionId,
        LocationId = r.LocationId,
        QualityFlag = r.QualityFlag,
        QualityNotes = r.QualityNotes,
        ExternalObservationKey = r.ExternalObservationKey };
    public static MeasurementRequest ToRequest(Measurement e) => new() { SourceRevisionId = e.SourceRevisionId ?? Guid.Empty,
        FactId = e.FactId,
        Value = e.Value,
        UpperValue = e.UpperValue,
        UnitId = e.UnitId,
        OriginalValue = e.OriginalValue,
        OriginalUnit = e.OriginalUnit,
        MeasurementKind = e.MeasurementKind,
        ObservedAt = e.ObservedAt,
        ObservationEndAt = e.ObservationEndAt,
        Instrument = e.Instrument ?? "",
        Context = e.Conditions,
        Uncertainty = e.Uncertainty,
        EvidenceType = e.EvidenceType,
        TestEnvironment = e.TestEnvironment,
        MissionId = e.MissionId,
        LocationId = e.LocationId,
        QualityFlag = e.QualityFlag ?? "",
        QualityNotes = e.QualityNotes,
        ExternalObservationKey = e.ExternalObservationKey };
