        Name = r.Name,
        Description = r.Description,
        ServiceUrl = r.ServiceUrl,
        LayerIdentifier = r.LayerIdentifier,
        TileMatrixSet = r.TileMatrixSet,
        Format = r.Format,
        Attribution = r.Attribution,
        Style = r.Style,
        ResourceUrlTemplate = r.ResourceUrlTemplate,
